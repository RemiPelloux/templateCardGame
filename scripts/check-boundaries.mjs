#!/usr/bin/env node
/**
 * Keeps the layers honest. Each folder may only import what the architecture allows:
 *
 *   engine, i18n → nothing (pure kernels)
 *   game, meta   → engine
 *   protocol     → engine, game, i18n, meta
 *   server       → engine, game, i18n, meta, protocol, Node
 *   web          → engine, game, i18n, meta, protocol, React, web-vitals, the PWA register
 *                  (never the server, never Node)
 *
 * Run by `pnpm lint:boundaries` and in CI. Exits 1 and lists every violation.
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const IMPORT =
  /(?:import|export)\s[^'"]*?from\s+['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g;

const SHARED = [
  '@cardgame/engine',
  '@cardgame/game',
  '@cardgame/i18n',
  '@cardgame/meta',
  '@cardgame/protocol',
];

const RULES = [
  { dir: 'packages/engine/src', allow: [] },
  { dir: 'packages/i18n/src', allow: [] },
  { dir: 'packages/game/src', allow: ['@cardgame/engine'] },
  { dir: 'packages/meta/src', allow: ['@cardgame/engine'] },
  {
    dir: 'packages/protocol/src',
    allow: [...SHARED.slice(0, 2), '@cardgame/i18n', '@cardgame/meta'],
  },
  {
    dir: 'apps/server/src',
    allow: [...SHARED, 'node:', 'better-sqlite3', 'sirv', 'vite'],
  },
  {
    dir: 'apps/web/src',
    allow: [
      ...SHARED,
      'react',
      'react-dom',
      '@tanstack/react-query',
      'web-vitals',
      // The service worker's registration, generated by vite-plugin-pwa at build time.
      'virtual:pwa-register',
    ],
  },
];

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (/\.(ts|tsx|mts)$/.test(name)) yield path;
  }
}

const allowed = (specifier, allow) =>
  specifier.startsWith('.') ||
  allow.some(
    (prefix) =>
      specifier === prefix || specifier.startsWith(prefix.endsWith(':') ? prefix : `${prefix}/`),
  );

const violations = RULES.flatMap(({ dir, allow }) =>
  [...files(join(root, dir))].flatMap((file) =>
    [...readFileSync(file, 'utf8').matchAll(IMPORT)]
      .map((match) => match[1] ?? match[2])
      .filter((specifier) => !allowed(specifier, allow))
      .map((specifier) => `${relative(root, file)} imports "${specifier}"`),
  ),
);

if (violations.length) {
  console.error(
    `Layer boundaries broken (see docs/architecture.md):\n  ${violations.join('\n  ')}`,
  );
  process.exit(1);
}
console.log('Layer boundaries respected.');
